#pragma once

// =============================================================
// encoder.h — квадратурний енкодер з кнопкою
//
// Polling через esp_timer (1мс) — безпечно для I2C LCD.
// Gray-code decoder з порогом 4 переходи на клік.
//
// encSteps — атомарний накопичувач обертання.
//   Таймер тільки накопичує кроки.
//   UI цикл читає і скидає значення.
//   Не губить імпульси при швидкому крутінні.
//
// evClick / evLong — прапорці подій кнопки.
//   Скидаються після читання в UI циклі.
// =============================================================

#include <cstdint>
#include <stdbool.h>

// Ініціалізація GPIO
void encoder_init();

// Опитування — викликається з esp_timer кожну 1мс
// Тільки читає енкодер і накопичує кроки.
// Ніякої бізнес-логіки.
void encoder_update();

// Атомарний накопичувач кроків.
// Позитивне = вправо, негативне = вліво.
// UI цикл читає і скидає: int32_t s = encSteps; encSteps = 0;
extern volatile int32_t encSteps;

// Прапорці подій кнопки — скидаються після читання
extern bool evClick;
extern bool evLong;