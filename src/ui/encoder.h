#pragma once

#include <stdint.h>
#include <stdbool.h>

// ─────────────────────────────────────────
// Модуль енкодера з кнопкою
//
// Енкодер: два сигнали A і B (квадратурний)
// Кнопка: вбудована в вісь енкодера
//
// Підтримує:
// - обертання вліво/вправо
// - короткий натиск кнопки
// - довгий натиск кнопки (> LONG_PRESS_MS)
// ─────────────────────────────────────────

// Довгий натиск — скільки мс тримати щоб спрацювало
#define LONG_PRESS_MS 800

// Ініціалізація GPIO енкодера
void encoder_init();

// Опитати стан енкодера і кнопки.
// Викликати кожні ~10 мс з ui_task.
void encoder_update();

// Повертає на скільки позицій прокрутили з останнього виклику.
// Позитивне — вправо/вгору, негативне — вліво/вниз.
// Скидається після виклику.
int8_t encoder_get_delta();

// Повертає true якщо був короткий натиск з останнього виклику.
// Скидається після виклику.
bool encoder_get_click();

// Повертає true якщо був довгий натиск з останнього виклику.
// Скидається після виклику.
bool encoder_get_long_press();