#pragma once

// =============================================================
// stepper.h — низькорівневе керування кроковиками
//
// Два мотори: шпиндель і каретка укладчика.
// Кожен має три сигнали: STEP, DIR, EN.
//
// Зараз: заглушка — логує кроки в Serial.
// Після приходу TMC2209: замінити тіла функцій на GPIO виклики.
// Інтерфейс залишиться без змін.
// =============================================================

// Ініціалізація GPIO (або заглушка)
void stepper_init();

// Один крок шпинделя в поточному напрямку
void spindle_step();

// Встановити напрямок шпинделя
// forward=true → CW, forward=false → CCW
void spindle_set_dir(bool forward);

// Увімкнути/вимкнути драйвер шпинделя
// EN активний LOW на TMC2209
void spindle_enable(bool en);

// Один крок каретки в поточному напрямку
void carriage_step();

// Встановити напрямок каретки
void carriage_set_dir(bool forward);

// Увімкнути/вимкнути драйвер каретки
void carriage_enable(bool en);