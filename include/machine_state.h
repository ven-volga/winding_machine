#pragma once

// =============================================================
// machine_state.h — глобальний стан машини
//
// Єдина структура що описує поточний стан намоточного станка.
// Живе в machine_state.cpp, доступна всім модулям через extern.
//
// Правила роботи зі станом:
//   - Читати можна з будь-якого модуля напряму
//   - Змінювати параметри руху (швидкість, діаметр) —
//     тільки через функції motion.h (вони перераховують ratio)
//   - Змінювати UI параметри (windingWidth) — напряму з ui.cpp
//   - Поля що змінюються в ISR або motion_task мають бути volatile
// =============================================================

#include <cstdint>
#include "config.h"

struct MachineState
{
    // ── Параметри намотки ────────────────────────────────────────

    // Діаметр дроту в мм.
    // Визначає крок укладчика на оберт шпинделя.
    // Змінювати через motion_set_wire_diameter() — не напряму.
    float wireDiameter = 0.20f;

    // Ширина зони намотки в мм.
    // При досягненні цієї ширини укладчик реверсує напрямок.
    float windingWidth = 30.0f;

    // Швидкість шпинделя в об/хв (цільова).
    // Змінювати через motion_set_spindle_speed() — не напряму.
    uint32_t spindleSpeed = 300;

    // ── Поточний стан руху ───────────────────────────────────────

    // Поточна позиція каретки укладчика в мм від home позиції.
    // Оновлюється в motion_update() після кожного кроку каретки.
    volatile float carriagePosition = 0.0f;

    // Лічильник витків поточного шару.
    // Збільшується на 1 за кожен повний оберт шпинделя.
    volatile uint32_t turns = 0;

    // Напрямок руху укладчика.
    // true  = вперед (FWD >>>)
    // false = назад  (REV <<<)
    bool directionForward = true;

    // Прапорець що машина зараз крутиться.
    // Встановлюється в motion_start(), скидається після гальмування.
    // Не змінювати напряму — тільки через motion_start/stop().
    volatile bool running = false;
};

// Єдиний екземпляр стану машини.
// Визначений в machine_state.cpp.
extern MachineState machineState;