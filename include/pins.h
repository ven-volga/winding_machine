#define BTN_SPINDLE_CW      4
#define BTN_SPINDLE_CCW     5
#define BTN_CARRIAGE_LEFT   23
#define BTN_CARRIAGE_RIGHT  15

// ─────────────────────────────────────────
// КНОПКА СЕРВІСНОЇ НАМОТКИ
//
// Тримаєш → мотає в заданому напрямку БЕЗ рахунку витків
// Відпустив → зупиняє
// Каретка може виходити за межі 0 і windingWidth
// Напрямок НЕ змінюється автоматично
// Підключення: GPIO 2 → кнопка → GND (PULLUP внутрішній)
// ─────────────────────────────────────────

#define BTN_SERVICE_WIND    2

// ─────────────────────────────────────────
// ТУМБЛЕР УТРИМАННЯ ШПИНДЕЛЯ
//
// ON  → шпиндель заблокований (TMC2209 тримає струм)
// OFF → шпиндель вільний (можна крутити рукою)
// Працює в сервісному режимі і при зупинці пошарового режиму
// Підключення: GPIO 3 → тумблер → GND (PULLUP внутрішній)
// УВАГА: GPIO 3 = RX0, при прошивці тумблер має бути OFF
// ─────────────────────────────────────────

#define SW_SPINDLE_HOLD     3

// ─────────────────────────────────────────
// ДАТЧИКИ ХОЛЛА (зарезервовано)
// ─────────────────────────────────────────

#define HALL_A_PIN          34  // input only
#define HALL_B_PIN          35  // input only

// ─────────────────────────────────────────
// АВАРІЙНА ЗУПИНКА (ESTOP)
//
// Один пін — кінцевики каретки і кнопка аварійної зупинки
// підключені паралельно.
// Спрацювання → миттєва зупинка всіх моторів.
// Підключення: GPIO 16 → кнопка/кінцевики → GND (PULLUP внутрішній)
// ─────────────────────────────────────────

#define ESTOP_PIN           17

