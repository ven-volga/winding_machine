// ─────────────────────────────────────────
// МОТОРИ
// ─────────────────────────────────────────

// Кількість повних кроків мотора на оберт.
// Для стандартного NEMA17 — завжди 200.
#define MOTOR_STEPS         200

// Мікрокроки TMC2209 (встановлюються фізично через MS1/MS2).
// 16 мікрокроків — хороший баланс між плавністю і швидкістю.
// Варіанти: 2, 4, 8, 16 (без UART)
// Якщо зміниш MS1/MS2 на драйвері — зміни і тут.
#define MICROSTEPS          16


// ─────────────────────────────────────────
// КІНЕМАТИКА ШПИНДЕЛЯ
// ─────────────────────────────────────────

// Передаточне відношення ременя шпинделя.
// 2.0 = мотор робить 2 оберти на 1 оберт шпинделя (передача 1:2).
// Якщо зміниш шківи — зміни це значення.
#define SPINDLE_RATIO       2.0f


// ─────────────────────────────────────────
// КІНЕМАТИКА УКЛАДЧИКА
// ─────────────────────────────────────────

// Крок гвинта T8 в мм за один оберт мотора укладчика.
// Для однозахідного T8 — 2.0 мм/оберт.
// Для чотирьохзахідного T8 — 8.0 мм/оберт.
#define T8_LEAD_MM          2.0f


// ─────────────────────────────────────────
// РОЗГІН І ГАЛЬМУВАННЯ (acceleration ramp)
// ─────────────────────────────────────────

// Початкова затримка між кроками при старті (мікросекунди).
// Визначає швидкість з якої починається розгін.
// Більше значення = повільніший старт = м'якший розгін.
// 8000 мкс ≈ 15-20 об/хв шпинделя — достатньо повільно
// щоб мотор гарантовано не пропустив перший крок.
// Якщо мотор смикається при старті — збільшуй це значення.
#define ACCEL_START_DELAY_US    8000

// На скільки мкс зменшувати затримку за кожен крок під час розгону.
// Більше значення = крутіший (коротший) розгін.
// Менше значення = плавніший (довший) розгін.
// 10 мкс — хороший старт для NEMA17 з моментом 0.4-0.55 Нм.
// Якщо мотор пропускає кроки під час розгону — зменшуй.
// Якщо розгін надто довгий — збільшуй.
#define ACCEL_STEP_US           10


// ─────────────────────────────────────────
// ДІАПАЗОНИ ПАРАМЕТРІВ НАМОТКИ
// ─────────────────────────────────────────

// Швидкість шпинделя (об/хв)
// Мінімум обмежений ACCEL_START_DELAY_US — надто мала швидкість
// може бути менша за початкову швидкість розгону.
#define SPINDLE_SPEED_MIN   10      // об/хв
#define SPINDLE_SPEED_MAX   600     // об/хв
#define SPINDLE_SPEED_STEP  10      // крок зміни в UI

// Діаметр дроту (мм)
// Визначає крок укладчика на оберт шпинделя.
#define WIRE_DIAMETER_MIN   0.05f   // мм (найтонший ПЕЛ)
#define WIRE_DIAMETER_MAX   3.00f   // мм (товстий обмотувальний)
#define WIRE_DIAMETER_STEP  0.01f   // крок зміни в UI

// Ширина намотки (мм)
// Максимум обмежений механічним ходом каретки.
// Підбери під реальний хід твоєї MGN12.
#define WINDING_WIDTH_MIN   1.0f    // мм
#define WINDING_WIDTH_MAX   200.0f  // мм — підкоригуй під свій хід каретки
#define WINDING_WIDTH_STEP  0.5f    // крок зміни в UI


// ─────────────────────────────────────────
// UI
// ─────────────────────────────────────────

// Період оновлення дисплею (мс).
// 100 мс = 10 разів на секунду — достатньо для відображення
// лічильника витків і позиції каретки без мерехтіння.
// Зменшуй якщо потрібне швидше оновлення (але навантажить I2C).
#define UI_REFRESH_MS       100

// Час довгого натиску кнопки енкодера (мс).
// Якщо незручно — підбери під себе.
#define LONG_PRESS_MS       800

// Час debounce кнопок (мс).
// Збільшуй якщо кнопки "брязкотять" (double click без натискання).
#define BTN_DEBOUNCE_MS     30
#define PEDAL_DEBOUNCE_MS   30